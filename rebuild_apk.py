#!/usr/bin/env python3
import os
import sys
import subprocess
import hashlib
import zlib
import zipfile
import shutil

ROOT_DIR = os.path.dirname(os.path.abspath(__file__))

def main():
    print("=== 1. Building Vite Production Bundle ===")
    res = subprocess.run(["npm", "run", "build"], cwd=ROOT_DIR)
    if res.returncode != 0:
        print("npm run build failed!")
        sys.exit(1)

    dist_dir = os.path.join(ROOT_DIR, "dist")
    if not os.path.exists(dist_dir):
        print("dist directory not found!")
        sys.exit(1)

    temp_dir = os.path.join(ROOT_DIR, "apk-temp")
    if os.path.exists(temp_dir):
        shutil.rmtree(temp_dir)
    os.makedirs(temp_dir, exist_ok=True)

    base_apk = os.path.join(ROOT_DIR, "public", "martha-fashion.apk")
    if not os.path.exists(base_apk):
        print(f"Base APK {base_apk} not found!")
        sys.exit(1)

    print("=== 2. Extracting Android Base APK Assets ===")
    with zipfile.ZipFile(base_apk, 'r') as z:
        for item in z.infolist():
            # Skip META-INF (will be regenerated by apksigner) and old web assets
            if item.filename.startswith("META-INF/") or item.filename.startswith("assets/web/"):
                continue
            z.extract(item, temp_dir)

    print("=== 3. Patching classes.dex with Live URL and Checksums ===")
    dex_path = os.path.join(temp_dir, "classes.dex")
    with open(dex_path, "rb") as f:
        dex = bytearray(f.read())

    # Replace dead ais-pre URL with active live ais-dev URL
    target_old = b"https://ais-pre-w4zmunnt4yz2wwv7weeuom-497052180324.europe-west2.run.app"
    target_new = b"https://ais-dev-w4zmunnt4yz2wwv7weeuom-497052180324.europe-west2.run.app"
    
    if target_old in dex:
        dex = bytearray(dex.replace(target_old, target_new))
        print(f"Successfully replaced ais-pre with ais-dev in classes.dex")
    else:
        print(f"ais-pre URL not found or already replaced in classes.dex")

    # Update Dalvik checksums
    dex[12:32] = hashlib.sha1(dex[32:]).digest()
    dex[8:12] = zlib.adler32(dex[12:]).to_bytes(4, 'little')

    with open(dex_path, "wb") as f:
        f.write(dex)

    print("=== 4. Injecting Fresh Web Application into APK Assets ===")
    web_assets_dir = os.path.join(temp_dir, "assets", "web")
    os.makedirs(web_assets_dir, exist_ok=True)

    # Read and adapt dist/index.html
    with open(os.path.join(dist_dir, "index.html"), "r", encoding="utf-8") as f:
        html = f.read()

    # Ensure all paths are relative
    html = html.replace('src="/', 'src="./').replace('href="/', 'href="./')
    html = html.replace('src="assets/', 'src="./assets/').replace('href="assets/', 'href="./assets/')

    with open(os.path.join(web_assets_dir, "index.html"), "w", encoding="utf-8") as f:
        f.write(html)

    # Copy dist assets
    dist_assets_dir = os.path.join(dist_dir, "assets")
    target_assets_dir = os.path.join(web_assets_dir, "assets")
    shutil.copytree(dist_assets_dir, target_assets_dir, dirs_exist_ok=True)

    # Copy public images/manifest if available
    public_dir = os.path.join(ROOT_DIR, "public")
    for fname in ["femme.jpg", "icon-192.png", "icon-512.png", "apple-touch-icon.png", "manifest.json"]:
        src = os.path.join(public_dir, fname)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(web_assets_dir, fname))

    # Also sync into android-build/assets/web for reproducibility
    android_build_assets = os.path.join(ROOT_DIR, "android-build", "assets", "web")
    os.makedirs(android_build_assets, exist_ok=True)
    shutil.copytree(web_assets_dir, android_build_assets, dirs_exist_ok=True)

    print("=== 5. Creating Clean Unaligned APK ===")
    unaligned_apk = os.path.join(temp_dir, "unaligned.apk")
    with zipfile.ZipFile(unaligned_apk, 'w', compression=zipfile.ZIP_DEFLATED) as zout:
        for root, dirs, files in os.walk(temp_dir):
            for file in files:
                if file in ["unaligned.apk", "aligned.apk"]:
                    continue
                full_path = os.path.join(root, file)
                rel_path = os.path.relpath(full_path, temp_dir)
                zout.write(full_path, rel_path)

    print("=== 6. Performing 4-byte zipalign ===")
    aligned_apk = os.path.join(temp_dir, "aligned.apk")
    res = subprocess.run(["zipalign", "-f", "-p", "4", unaligned_apk, aligned_apk])
    if res.returncode != 0:
        print("zipalign failed!")
        sys.exit(1)

    print("=== 7. Signing APK with apksigner and martha.keystore ===")
    keystore_path = os.path.join(ROOT_DIR, "martha.keystore")
    target_apk = os.path.join(ROOT_DIR, "public", "martha-fashion.apk")
    
    sign_cmd = [
        "apksigner", "sign",
        "--ks", keystore_path,
        "--ks-pass", "pass:martha2024",
        "--key-pass", "pass:martha2024",
        "--out", target_apk,
        aligned_apk
    ]
    res = subprocess.run(sign_cmd)
    if res.returncode != 0:
        print("apksigner failed!")
        sys.exit(1)

    print("=== 8. Verifying APK Signature ===")
    res = subprocess.run(["apksigner", "verify", "--verbose", target_apk])
    if res.returncode != 0:
        print("apksigner verification failed!")
        sys.exit(1)

    print(f"\nSUCCESS! Martha Fashion APK compiled & signed successfully at:\n{target_apk}")
    print(f"File size: {os.path.getsize(target_apk)} bytes")

    # Cleanup temp dir
    shutil.rmtree(temp_dir, ignore_errors=True)

if __name__ == "__main__":
    main()
